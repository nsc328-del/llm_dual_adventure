function buildBoxShadow(shadowStr: string, pixelSize: number): string {
  return shadowStr.split(', ').map(entry => {
    const parts = entry.trim().split(' ');
    const x = parseInt(parts[0]) * pixelSize;
    const y = parseInt(parts[1]) * pixelSize;
    const spread = parts.length > 4 ? parts[3] : '0';
    const color = parts.length > 4 ? parts[4] : parts[2];
    return `${x}px ${y}px 0 ${spread === '0' ? '' : spread + 'px '}${color}`;
  }).join(', ');
}

interface PixelAvatarProps {
  avatarId: string;
  size?: number;
}

export function PixelAvatar({ avatarId, size = 28 }: PixelAvatarProps) {
  const avatar = AVATARS[avatarId] || AVATARS.warrior;
  const pixelSize = Math.max(2, Math.floor(size / 7));

  return (
    <div
      style={{
        width: size,
        height: size,
        position: 'relative',
        flexShrink: 0,
      }}
    >
      <div
        style={{
          position: 'absolute',
          top: 0,
          left: 0,
          width: `${pixelSize}px`,
          height: `${pixelSize}px`,
          boxShadow: buildBoxShadow(avatar.shadow, pixelSize),
        }}
      />
    </div>
  );
}
